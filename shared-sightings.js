window.BF_RECENT_SINCE = "2026-05-01";
window.BF_YEAR = "2026";

window.BF_inWindow = function (s, range) {
  if (range === "recent") return s.postedOn >= window.BF_RECENT_SINCE;
  if (range === "year") return String(s.sightingOn).slice(0, 4) === window.BF_YEAR;
  return true;
};

window.BF_NEAR_MILES = 150;
window.BF_EARTH_MILES = 3958.7613;

window.BF_milesBetween = function (lat1, lng1, lat2, lng2) {
  const toRad = function (d) {
    return (d * Math.PI) / 180;
  };
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) * Math.sin(dLng / 2);
  return 2 * window.BF_EARTH_MILES * Math.asin(Math.min(1, Math.sqrt(a)));
};

window.BF_nearOrigin = function (sightings, origin, miles) {
  const radius = miles == null ? window.BF_NEAR_MILES : miles;
  return sightings.filter(function (s) {
    return window.BF_milesBetween(origin.lat, origin.lng, s.lat, s.lng) <= radius;
  });
};

window.BF_formatMiles = function (miles) {
  if (miles < 1) return "under 1 mi";
  return Math.round(miles) + " mi";
};

window.BF_esc = function (str) {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/"/g, "&quot;");
};

window.BF_formatWhen = function (s) {
  const iso = s.sightingOn;
  const d = new Date(iso + "T12:00:00");
  let date;
  if (s.sightingPrecision === "day") {
    date = d.toLocaleDateString("en-US", {
      weekday: "short",
      month: "short",
      day: "numeric",
      year: "numeric",
    });
  } else if (s.sightingPrecision === "year") {
    date = String(d.getFullYear());
  } else {
    date = d.toLocaleDateString("en-US", { month: "long", year: "numeric" });
  }
  return { date: date, time: s.sightingTime || "Not reported" };
};

