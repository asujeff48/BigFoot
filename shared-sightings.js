window.BF_classLegendHtml = function () {
  return Object.keys(window.BF_CLASSES)
    .map(function (code) {
      const c = window.BF_CLASSES[code];
      return "<dt>" + window.BF_esc(c.label) + "</dt><dd>" + window.BF_esc(c.meaning) + "</dd>";
    })
    .join("");
};

window.BF_popupFields = function (s) {
  const when = window.BF_formatWhen(s);
  const klass = window.BF_CLASSES[s.classCode] || window.BF_CLASSES.B;
  return {
    location: s.place + " — " + s.region,
    date: when.date,
    time: when.time,
    type: s.type,
    klass: klass.label,
    classMeaning: klass.meaning,
    url: s.url,
  };
};

/**
 * Mid-stride walking Bigfoot marker (side profile silhouette).
 * Uses an inline SVG tint so the transparent PNG stays a figure, not a block.
 * opts.glow — IR-style halo (Trail Cam). opts.shadow — hard offset (Contour Ops).
 */
window.BF_markerSvg = function (fill, width, height, opts) {
  const w = width || 52;
  const h = height || 64;
  const color = fill || "#6dff9a";
  const hex = String(color).replace("#", "");
  const r = (parseInt(hex.slice(0, 2), 16) / 255).toFixed(4);
  const g = (parseInt(hex.slice(2, 4), 16) / 255).toFixed(4);
  const b = (parseInt(hex.slice(4, 6), 16) / 255).toFixed(4);
  const extra = opts || {};
  const uid = "bfm-" + Math.random().toString(36).slice(2, 9);

  let extras = "";
  if (extra.glow) {
    extras = `<feDropShadow in="tinted" dx="0" dy="0" stdDeviation="0.9" flood-color="${color}" flood-opacity="0.85"/>`;
  } else if (extra.shadow) {
    extras = `<feDropShadow in="tinted" dx="0" dy="1.5" stdDeviation="0.4" flood-color="#000000" flood-opacity="0.55"/>`;
  }

  return `
    <svg class="bf-silhouette" xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" overflow="visible" aria-hidden="true" focusable="false">
      <defs>
        <filter id="${uid}" x="-25%" y="-25%" width="150%" height="150%" color-interpolation-filters="sRGB">
          <feColorMatrix in="SourceGraphic" type="matrix" result="tinted"
            values="0 0 0 0 ${r}  0 0 0 0 ${g}  0 0 0 0 ${b}  0 0 0 1 0"/>
          ${extras}
        </filter>
      </defs>
      <image href="./walking-bigfoot-icon.png?v=4" width="${w}" height="${h}" preserveAspectRatio="xMidYMax meet" filter="url(#${uid})"/>
    </svg>`;
};
